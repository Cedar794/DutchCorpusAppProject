alter table public.lemma_examples enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'lemma_examples'
      and policyname = 'public read lemma_examples'
  ) then
    create policy "public read lemma_examples" on public.lemma_examples
    for select to anon, authenticated using (true);
  end if;
end;
$$;

grant select on public.lemma_examples to anon, authenticated;
