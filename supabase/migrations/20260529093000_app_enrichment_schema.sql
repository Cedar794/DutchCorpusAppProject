-- Dutch lexicon application enrichment schema.
-- Adds app-facing metadata without replacing the source-preserving lexicon tables.

alter table public.pos_tags
  add column if not exists app_pos text,
  add column if not exists app_pos_label_zh text,
  add column if not exists app_pos_label_en text,
  add column if not exists display_order integer,
  add column if not exists is_content_pos boolean not null default false;

alter table public.forms
  add column if not exists app_form_role text,
  add column if not exists display_label_zh text,
  add column if not exists display_label_en text,
  add column if not exists morph_features jsonb not null default '{}'::jsonb,
  add column if not exists is_observed boolean not null default false;

alter table public.senses
  add column if not exists app_sense_order integer,
  add column if not exists is_core boolean not null default false,
  add column if not exists display_definition_nl text,
  add column if not exists dedupe_key text,
  add column if not exists merged_into_sense_id bigint references public.senses(id) on delete set null;

alter table public.sense_translations
  add column if not exists review_status text not null default 'unreviewed'
    check (review_status in ('unreviewed', 'accepted', 'needs_review', 'rejected')),
  add column if not exists translation_style text not null default 'learner_dictionary',
  add column if not exists raw_payload jsonb not null default '{}'::jsonb;

create unique index if not exists sense_translations_sense_lang_source_unique
  on public.sense_translations (sense_id, lang, source_id)
  where source_id is not null;

create index if not exists pos_tags_app_pos_idx on public.pos_tags (app_pos);
create index if not exists forms_app_form_role_idx on public.forms (app_form_role);
create index if not exists senses_app_default_idx
  on public.senses (lemma_pos_entry_id, app_sense_order)
  where merged_into_sense_id is null;
create index if not exists senses_dedupe_key_idx on public.senses (lemma_pos_entry_id, dedupe_key);

create table if not exists public.lemma_examples (
  id bigserial primary key,
  lemma_id bigint not null references public.lemmas(id) on delete cascade,
  lemma_pos_entry_id bigint references public.lemma_pos_entries(id) on delete cascade,
  form_id bigint references public.forms(id) on delete set null,
  ex_nl text not null,
  source_id bigint references public.sources(id) on delete set null,
  external_id text,
  quality_score numeric(4,3)
    check (quality_score is null or (quality_score >= 0 and quality_score <= 1)),
  is_active boolean not null default true,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (lemma_id, lemma_pos_entry_id, ex_nl)
);

create index if not exists lemma_examples_lemma_id_idx on public.lemma_examples (lemma_id);
create index if not exists lemma_examples_lemma_pos_entry_id_idx on public.lemma_examples (lemma_pos_entry_id);
create index if not exists lemma_examples_quality_idx on public.lemma_examples (quality_score desc nulls last);
create unique index if not exists sense_relations_unique_app_idx
  on public.sense_relations (
    sense_id_from,
    coalesce(sense_id_to, 0),
    coalesce(target_external_id, ''),
    relation_type,
    coalesce(source_id, 0)
  );

drop trigger if exists lemma_examples_set_updated_at on public.lemma_examples;
create trigger lemma_examples_set_updated_at
before update on public.lemma_examples
for each row execute function public.set_updated_at();

