  nullif(notes, ''),
  source_id,
  external_id,
  confidence::numeric,
  coalesce(nullif(review_status, ''), 'unreviewed'),
  coalesce(nullif(raw_payload, '')::jsonb, '{}'::jsonb),
  case when target_lemma_id is not null then 'inserted_lemma_relation' else 'unresolved_target' end
from resolved
on conflict (source_id, external_id) do update
set
  source_lemma_id = excluded.source_lemma_id,
  target_lemma_id = excluded.target_lemma_id,
  target_text_nl = excluded.target_text_nl,
  relation_type = excluded.relation_type,
  notes = excluded.notes,
  confidence = excluded.confidence,
  review_status = excluded.review_status,
  raw_payload = excluded.raw_payload,
  import_status = excluded.import_status,
  updated_at = now();

with resolved as (
  select
    stg.*,
    src_l.id as source_lemma_id,
    target_l.id as target_lemma_id,
    src.id as source_id
  from stg_aigc_relations stg
  join public.lemmas src_l on src_l.lemma_norm = stg.source_lemma_norm
  join public.lemmas target_l on target_l.lemma_norm = stg.target_lemma_norm
  join public.sources src on src.source_key = stg.source_key
)
insert into public.lemma_relations (
  lemma_id_from,
  lemma_id_to,
  relation_type,
  source_id,
  external_id,
  confidence,
  notes
)
select
  source_lemma_id,
  target_lemma_id,
  relation_type,
  source_id,
  external_id,
  confidence::numeric,
  nullif(notes, '')
from resolved
on conflict (lemma_id_from, lemma_id_to, relation_type, source_id)
do update set
  external_id = excluded.external_id,
  confidence = excluded.confidence,
  notes = excluded.notes;

with ordered_senses as (
  select
    s.id,
    row_number() over (
      partition by s.lemma_pos_entry_id
      order by
        s.is_primary desc,
        case when s.display_definition_nl is not null then 0 else 1 end,
        case src.source_key when 'odwn_1_3' then 1 when 'dbnary_nld_2026_05' then 2 when 'aigc_missing_definition_v1' then 8 else 9 end,
        nullif(regexp_replace(coalesce(s.sense_no, ''), '[^0-9]', '', 'g'), '')::integer nulls last,
        s.id
    ) as sense_order
  from public.senses s
  join public.sources src on src.id = s.source_id
  where s.merged_into_sense_id is null
)
update public.senses s
set
  app_sense_order = o.sense_order,
  is_core = o.sense_order <= 3
from ordered_senses o
where s.id = o.id;

