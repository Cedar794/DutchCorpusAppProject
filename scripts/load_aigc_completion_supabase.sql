declare
  missing_count integer;
begin
  select count(*) into missing_count
  from (
    select definition_nl_aigc value from stg_aigc_sense_definitions
    union all select usage_note_aigc from stg_aigc_sense_definitions where nullif(usage_note_aigc, '') is not null
    union all select gloss from stg_aigc_sense_translations
    union all select explanation from stg_aigc_sense_translations
    union all select definition_nl from stg_aigc_new_sense_candidates
    union all select usage_note from stg_aigc_new_sense_candidates where nullif(usage_note, '') is not null
    union all select gloss from stg_aigc_new_sense_translations
    union all select explanation from stg_aigc_new_sense_translations
    union all select ex_nl from stg_aigc_examples
    union all select translation from stg_aigc_example_translations
    union all select target_text_nl from stg_aigc_relations where nullif(target_text_nl, '') is not null
    union all select notes from stg_aigc_relations where nullif(notes, '') is not null
  ) generated
  where value is not null
    and btrim(value) !~ '#aigc\s*$';

  if missing_count > 0 then
    raise exception 'AIGC marker validation failed: % generated fields missing terminal #aigc', missing_count;
  end if;
end $$;

