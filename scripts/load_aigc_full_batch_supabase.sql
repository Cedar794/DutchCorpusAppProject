create temp table stg_sense_translations_deduped on commit drop as
select
  batch_id,
  sense_id,
  lemma_norm,
  pos,
  lang,
  gloss,
  explanation,
  translation_style,
  confidence,
  review_status,
  source_key,
  external_id,
  raw_payload
from (
  select
    stg.*,
    row_number() over (
      partition by stg.sense_id, stg.lang, stg.source_key
      order by
        case when stg.external_id like '%_p0_%' then 0 else 1 end,
        stg.external_id
    ) as rn
  from stg_sense_translations stg
) ranked
where rn = 1;

do $$
declare
  missing_count integer;
begin
  select count(*) into missing_count
  from (
    select definition_nl_aigc value from stg_sense_definitions where nullif(definition_nl_aigc, '') is not null
    union all select usage_note_aigc from stg_sense_definitions where nullif(usage_note_aigc, '') is not null
    union all select gloss from stg_sense_translations where nullif(gloss, '') is not null
    union all select explanation from stg_sense_translations where nullif(explanation, '') is not null
    union all select ex_nl from stg_sense_examples where nullif(ex_nl, '') is not null
    union all select translation from stg_example_translations where nullif(translation, '') is not null
    union all select translation from stg_generated_example_translations where nullif(translation, '') is not null
  ) generated
  where btrim(value) !~ '#aigc\s*$';

  if missing_count > 0 then
    raise exception 'AIGC full batch marker validation failed: % generated fields missing terminal #aigc', missing_count;
  end if;
end $$;

with resolved as (
  select
    stg.*,
    s.id as target_sense_id
  from stg_sense_definitions stg
  join public.senses s on s.id = stg.sense_id::bigint
)
update public.senses s
set
  definition_nl = r.definition_nl_aigc,
  usage_note = nullif(r.usage_note_aigc, ''),
  display_definition_nl = r.definition_nl_aigc,
  dedupe_key = regexp_replace(lower(btrim(replace(r.definition_nl_aigc, '#aigc', ''))), '\s+', ' ', 'g'),
  review_status = coalesce(nullif(r.review_status, ''), 'unreviewed'),
  raw_payload = jsonb_set(
    s.raw_payload,
    '{aigc_full_batch}',
    jsonb_build_object(
      'batch_id', r.batch_id,
      'external_id', r.external_id,
      'source_key', r.source_key,
      'definition_nl', r.definition_nl_aigc,
      'usage_note', r.usage_note_aigc,
      'confidence', r.confidence::numeric,
      'raw_payload', coalesce(nullif(r.raw_payload, '')::jsonb, '{}'::jsonb)
    ),
    true
  )
from resolved r
where s.id = r.target_sense_id
  and coalesce(btrim(s.definition_nl), '') = '';

