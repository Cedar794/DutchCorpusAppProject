\set ON_ERROR_STOP on

\set batch_dir '/tmp/dutch_lexicon_import/aigc_agent_replacement'

begin;

insert into public.sources (source_key, name, source_type, version, notes)
values
  ('aigc_subagent_definition_v1', 'AIGC subagent replacement definitions v1', 'aigc_derived', '2026-06-14', 'High-quality subagent replacement definitions; generated fields carry #aigc markers.'),
  ('aigc_subagent_missing_sense_v1', 'AIGC subagent replacement missing senses v1', 'aigc_derived', '2026-06-14', 'High-quality subagent replacement for previously script-created missing senses; generated fields carry #aigc markers.'),
  ('aigc_subagent_sense_translation_v1', 'AIGC subagent replacement sense translations v1', 'aigc_derived', '2026-06-14', 'High-quality subagent replacement Chinese learner translations; generated fields carry #aigc markers.'),
  ('aigc_subagent_examples_v1', 'AIGC subagent replacement examples v1', 'aigc_derived', '2026-06-14', 'High-quality subagent replacement Dutch examples; generated fields carry #aigc markers.'),
  ('aigc_subagent_example_translation_v1', 'AIGC subagent replacement example translations v1', 'aigc_derived', '2026-06-14', 'High-quality subagent replacement Chinese example translations; generated fields carry #aigc markers.')
on conflict (source_key) do update
set
  name = excluded.name,
  source_type = excluded.source_type,
  version = excluded.version,
  notes = excluded.notes,
  updated_at = now();

create table if not exists public.aigc_agent_replacement_imports (
  id bigint generated by default as identity primary key,
  batch_id text not null,
  item_type text not null,
  target_id bigint not null,
  source_key text not null,
  confidence numeric(4,3) not null,
  quality_note text,
  imported_at timestamptz not null default now(),
  unique (batch_id, item_type, target_id)
);

alter table public.aigc_agent_replacement_imports enable row level security;
grant select on public.aigc_agent_replacement_imports to anon, authenticated;
drop policy if exists "public read aigc_agent_replacement_imports" on public.aigc_agent_replacement_imports;
create policy "public read aigc_agent_replacement_imports"
on public.aigc_agent_replacement_imports
for select to anon, authenticated
using (true);

create temp table stg_sense_replacements (
  batch_id text,
  sense_id text,
  translation_id text,
  example_id text,
  example_translation_id text,
  lemma_norm text,
  pos text,
  definition_nl text,
  usage_note text,
  gloss_zh text,
  explanation_zh text,
  ex_nl text,
  ex_zh text,
  confidence text,
  quality_note text
) on commit drop;

create temp table stg_example_translation_replacements (
  batch_id text,
  translation_id text,
  example_id text,
  sense_id text,
  lemma_norm text,
  pos text,
  translation_zh text,
  confidence text,
  quality_note text
) on commit drop;

\copy stg_sense_replacements from '/tmp/dutch_lexicon_import/aigc_agent_replacement/sense_replacements.tsv' with (format csv, delimiter E'\t', header true)
\copy stg_example_translation_replacements from '/tmp/dutch_lexicon_import/aigc_agent_replacement/example_translation_replacements.tsv' with (format csv, delimiter E'\t', header true)

do $$
declare
  missing_count integer;
begin
  select count(*) into missing_count
  from (
    select definition_nl value from stg_sense_replacements where nullif(definition_nl, '') is not null
    union all select usage_note from stg_sense_replacements where nullif(usage_note, '') is not null
    union all select gloss_zh from stg_sense_replacements where nullif(gloss_zh, '') is not null
    union all select explanation_zh from stg_sense_replacements where nullif(explanation_zh, '') is not null
    union all select ex_nl from stg_sense_replacements where nullif(ex_nl, '') is not null
    union all select ex_zh from stg_sense_replacements where nullif(ex_zh, '') is not null
    union all select quality_note from stg_sense_replacements where nullif(quality_note, '') is not null
    union all select translation_zh from stg_example_translation_replacements where nullif(translation_zh, '') is not null
    union all select quality_note from stg_example_translation_replacements where nullif(quality_note, '') is not null
  ) generated
  where btrim(value) !~ '#aigc\s*$';

  if missing_count > 0 then
    raise exception 'AIGC subagent replacement marker validation failed: % generated fields missing terminal #aigc', missing_count;
  end if;
end $$;

create temp table stg_sense_deduped on commit drop as
select *
from (
  select
    stg.*,
    row_number() over (partition by stg.sense_id order by stg.batch_id) as rn
  from stg_sense_replacements stg
  where nullif(stg.sense_id, '') is not null
) ranked
where rn = 1;

create temp table stg_example_translation_deduped on commit drop as
select *
from (
  select
    stg.*,
    row_number() over (partition by stg.translation_id order by stg.batch_id) as rn
  from stg_example_translation_replacements stg
  where nullif(stg.translation_id, '') is not null
) ranked
where rn = 1;

with replacement_sources as (
  select
    (select id from public.sources where source_key = 'aigc_subagent_missing_sense_v1') as missing_sense_source_id
),
resolved as (
  select
    stg.*,
    s.id as target_sense_id,
    src.source_key as current_source_key,
    s.raw_payload
  from stg_sense_deduped stg
  join public.senses s on s.id = stg.sense_id::bigint
  join public.sources src on src.id = s.source_id
)
update public.senses s
set
  definition_nl = r.definition_nl,
  usage_note = r.usage_note,
  display_definition_nl = r.definition_nl,
  dedupe_key = regexp_replace(lower(btrim(replace(r.definition_nl, '#aigc', ''))), '\s+', ' ', 'g'),
  source_id = case
    when r.current_source_key in ('aigc_missing_sense_v2', 'aigc_subagent_missing_sense_v1') then replacement_sources.missing_sense_source_id
    else s.source_id
  end,
  confidence = greatest(s.confidence, least(0.900, greatest(0.000, r.confidence::numeric))),
  review_status = 'needs_review',
  raw_payload = jsonb_set(
    s.raw_payload,
    '{aigc_subagent_replacement}',
    jsonb_build_object(
      'batch_id', r.batch_id,
      'source_key', case when r.current_source_key in ('aigc_missing_sense_v2', 'aigc_subagent_missing_sense_v1') then 'aigc_subagent_missing_sense_v1' else 'aigc_subagent_definition_v1' end,
      'confidence', r.confidence::numeric,
      'quality_note', r.quality_note
    ),
    true
  ),
  updated_at = now()
from resolved r
cross join replacement_sources
where s.id = r.target_sense_id
  and (
    s.raw_payload#>>'{aigc_full_batch,batch_id}' = 'aigc_full_bulk_remaining_0002'
    or r.current_source_key in ('aigc_missing_sense_v2', 'aigc_subagent_missing_sense_v1')
  );

with src as (
  select id from public.sources where source_key = 'aigc_subagent_sense_translation_v1'
),
resolved as (
  select stg.*, t.id as target_translation_id
  from stg_sense_deduped stg
  join public.sense_translations t on t.id = nullif(stg.translation_id, '')::bigint
)
update public.sense_translations t
set
  gloss = r.gloss_zh,
  explanation = r.explanation_zh,
  source_id = src.id,
  external_id = concat('subagent_', r.batch_id, '_tr_', r.translation_id),
  confidence = r.confidence::numeric,
  review_status = 'needs_review',
  translation_style = 'learner_dictionary',
  raw_payload = jsonb_build_object(
    'generator', r.batch_id,
    'aigc', true,
    'marker', '#aigc',
    'quality_note', r.quality_note
  ),
  updated_at = now()
from resolved r
cross join src
where t.id = r.target_translation_id;

with src as (
  select id from public.sources where source_key = 'aigc_subagent_examples_v1'
),
resolved as (
  select stg.*, e.id as target_example_id
  from stg_sense_deduped stg
  join public.examples e on e.id = nullif(stg.example_id, '')::bigint
)
update public.examples e
set
  ex_nl = r.ex_nl,
  source_id = src.id,
  external_id = concat('subagent_', r.batch_id, '_ex_', r.example_id),
  quality_score = r.confidence::numeric,
  raw_payload = jsonb_build_object(
    'generator', r.batch_id,
    'aigc', true,
    'marker', '#aigc',
    'quality_note', r.quality_note
  ),
  updated_at = now()
from resolved r
cross join src
where e.id = r.target_example_id;

with src as (
  select id from public.sources where source_key = 'aigc_subagent_example_translation_v1'
),
resolved as (
  select stg.*, et.id as target_example_translation_id
  from stg_sense_deduped stg
  join public.example_translations et on et.id = nullif(stg.example_translation_id, '')::bigint
)
update public.example_translations et
set
  translation = r.ex_zh,
  source_id = src.id,
  external_id = concat('subagent_', r.batch_id, '_extr_', r.example_translation_id),
  updated_at = now()
from resolved r
cross join src
where et.id = r.target_example_translation_id;

with src as (
  select id from public.sources where source_key = 'aigc_subagent_example_translation_v1'
),
resolved as (
  select stg.*, et.id as target_example_translation_id
  from stg_example_translation_deduped stg
  join public.example_translations et on et.id = stg.translation_id::bigint
)
update public.example_translations et
set
  translation = r.translation_zh,
  source_id = src.id,
  external_id = concat('subagent_', r.batch_id, '_extr_', r.translation_id),
  updated_at = now()
from resolved r
cross join src
where et.id = r.target_example_translation_id;

insert into public.aigc_agent_replacement_imports (batch_id, item_type, target_id, source_key, confidence, quality_note)
select batch_id, 'sense', sense_id::bigint, 'aigc_subagent_definition_v1', confidence::numeric, quality_note
from stg_sense_deduped
on conflict (batch_id, item_type, target_id) do update
set confidence = excluded.confidence, quality_note = excluded.quality_note, imported_at = now();

insert into public.aigc_agent_replacement_imports (batch_id, item_type, target_id, source_key, confidence, quality_note)
select batch_id, 'example_translation', translation_id::bigint, 'aigc_subagent_example_translation_v1', confidence::numeric, quality_note
from stg_example_translation_deduped
on conflict (batch_id, item_type, target_id) do update
set confidence = excluded.confidence, quality_note = excluded.quality_note, imported_at = now();

select 'sense_replacements_staged' as metric, count(*) as rows from stg_sense_replacements
union all
select 'example_translation_replacements_staged', count(*) from stg_example_translation_replacements
union all
select 'subagent_replacement_import_audit_rows', count(*) from public.aigc_agent_replacement_imports;

commit;
